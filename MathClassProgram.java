package module1.basic.javaconcepts;
public class MathClassProgram 
{
	public static void main(String[] args) 
	{
			System.out.println(Math.addExact(100, 200));
		int sum=Math.addExact(10, 20);
		System.out.println(sum);
		System.out.println(Math.subtractExact(200,100));
		System.out.println(Math.multiplyExact(10, 20));
		System.out.println(Math.max(10.8, 100.76));
		System.out.println(Math.min(10, 176));
		System.out.println(Math.abs(-9876));
		System.out.println(Math.random());
		System.out.println(Math.PI);
		
		
		double answer=	Math.sqrt(9876);
		System.out.println(answer);
	}
}
